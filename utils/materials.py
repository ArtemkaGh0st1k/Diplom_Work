"""Дисперсионные формулы материалов."""


def n_bk7(lambda_um: float) -> float:
    """
    Показатель преломления стекла BK7 по формуле Селлмейера.

    :param lambda_um: длина волны в микрометрах
    """
    B1, B2, B3 = 1.03961212, 0.231792344, 1.01046945
    C1, C2, C3 = 6.00069867e-3, 2.00179144e-2, 1.03560653e2
    l2 = lambda_um ** 2
    n2 = 1 + (B1 * l2) / (l2 - C1) + (B2 * l2) / (l2 - C2) + (B3 * l2) / (l2 - C3)
    return n2 ** 0.5
